/** Shown latitude range (the map is cropped: no fires near the poles). */
export const MAP_LAT = { top: 84, bottom: -58 };

export const px = (lon: number) => lon + 180;
export const py = (lat: number) => 90 - lat;

/** SVG path "d" for a list of polygons. */
export const pathOf = (polys: Pt[][]) =>
  polys.map((p) => "M" + p.map(([lo, la]) => `${px(lo).toFixed(1)},${py(la).toFixed(1)}`).join("L") + "Z").join("");
